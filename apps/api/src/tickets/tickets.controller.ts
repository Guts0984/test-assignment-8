import {
  Body,
  Controller,
  Get,
  HttpCode,
  Inject,
  Param,
  Patch,
  Post,
  Query,
  Req,
  Res,
} from '@nestjs/common';
import { ApiBody, ApiOperation, ApiQuery, ApiTags } from '@nestjs/swagger';
import type { DbHandle } from '@helpdesk/db';
import {
  bulkRequestSchema,
  createMessageSchema,
  createTicketSchema,
  listTicketsQuerySchema,
  patchTicketSchema,
  ratingSchema,
  uuidSchema,
  type BulkRequest,
  type CreateMessageInput,
  type CreateTicketInput,
  type ListTicketsQuery,
  type PatchTicketInput,
  type RatingInput,
} from '@helpdesk/shared';
import type { Request, Response } from 'express';
import { sql } from 'drizzle-orm';
import { Roles } from '../auth/decorators';
import { ZodPipe } from '../http/zod.pipe';
import { jsonSchemaOf } from '../http/swagger';
import { appError } from '../lib/errors';
import type { SessionUser } from '../lib/sessions';
import { TOKENS } from '../tokens';
import { listTickets } from './list';
import { bulkApply, takeNext } from './queue';
import { createTicket, getTicketDetail, patchTicket, postMessage } from './service';
import { fetchTicket } from './mutate';

const uuidParam = new ZodPipe(uuidSchema);
const user = (req: Request): SessionUser => {
  if (!req.auth) throw new Error('auth guard did not run');
  return req.auth.user;
};

@ApiTags('tickets')
@Controller('tickets')
export class TicketsController {
  constructor(@Inject(TOKENS.DB) private readonly db: DbHandle) {}

  @Get()
  @ApiOperation({ summary: 'List tickets (filters, full-text search, keyset pagination)' })
  @ApiQuery({ name: 'q', required: false })
  list(@Req() req: Request, @Query(new ZodPipe(listTicketsQuerySchema)) query: ListTicketsQuery) {
    return listTickets(this.db, user(req), query);
  }

  @Post()
  @Roles('customer')
  @ApiOperation({
    summary:
      'Create a ticket (customers). Repeating the same clientMessageId returns the same ticket.',
  })
  @ApiBody({ schema: jsonSchemaOf(createTicketSchema) })
  async create(
    @Req() req: Request,
    @Res({ passthrough: true }) res: Response,
    @Body(new ZodPipe(createTicketSchema)) body: CreateTicketInput,
  ) {
    const out = await createTicket({ db: this.db }, user(req), body);
    res.status(out.replayed ? 200 : 201);
    return out.ticket;
  }

  // Static paths first: they must not be swallowed by `:id`.
  @Post('take-next')
  @Roles('agent', 'lead')
  @HttpCode(200)
  @ApiOperation({ summary: 'Assign the most urgent free ticket of my categories to me (atomic)' })
  takeNext(@Req() req: Request) {
    return takeNext(this.db, user(req));
  }

  @Post('bulk')
  @Roles('agent', 'lead')
  @HttpCode(200)
  @ApiOperation({
    summary: 'Apply one action to up to 200 tickets; per-ticket result with skip reasons',
  })
  @ApiBody({ schema: jsonSchemaOf(bulkRequestSchema) })
  bulk(@Req() req: Request, @Body(new ZodPipe(bulkRequestSchema)) body: BulkRequest) {
    return bulkApply(this.db, user(req), body);
  }

  @Get(':id')
  @ApiOperation({ summary: 'Ticket with its conversation (internal notes only for staff)' })
  detail(@Req() req: Request, @Param('id', uuidParam) id: string) {
    return getTicketDetail({ db: this.db }, user(req), id);
  }

  @Patch(':id')
  @ApiOperation({
    summary: 'Change a ticket. Requires the version you last saw; 409 + current state otherwise.',
  })
  @ApiBody({ schema: jsonSchemaOf(patchTicketSchema) })
  patch(
    @Req() req: Request,
    @Param('id', uuidParam) id: string,
    @Body(new ZodPipe(patchTicketSchema)) body: PatchTicketInput,
  ) {
    return patchTicket({ db: this.db }, user(req), id, body);
  }

  @Post(':id/messages')
  @ApiOperation({
    summary:
      'Reply or add an internal note. `id` is generated by the client: a repeat never creates a second message.',
  })
  @ApiBody({ schema: jsonSchemaOf(createMessageSchema) })
  async message(
    @Req() req: Request,
    @Res({ passthrough: true }) res: Response,
    @Param('id', uuidParam) id: string,
    @Body(new ZodPipe(createMessageSchema)) body: CreateMessageInput,
  ) {
    const out = await postMessage({ db: this.db }, user(req), id, body);
    res.status(out.created ? 201 : 200);
    return out.result;
  }

  @Post(':id/read')
  @Roles('customer')
  @HttpCode(204)
  @ApiOperation({ summary: 'Mark the conversation as read (clears the "unread reply" highlight)' })
  async markRead(@Req() req: Request, @Param('id', uuidParam) id: string): Promise<void> {
    const u = user(req);
    if (!(await fetchTicket(this.db.db, u, id)))
      throw appError(404, 'not_found', 'Ticket not found');
    await this.db.db.execute(sql`
      INSERT INTO ticket_reads (user_id, ticket_id, last_read_at) VALUES (${u.id}, ${id}, now())
      ON CONFLICT (user_id, ticket_id) DO UPDATE SET last_read_at = now()`);
  }

  @Post(':id/rating')
  @Roles('customer')
  @ApiOperation({ summary: 'Rate a resolved ticket 1–5 (once)' })
  @ApiBody({ schema: jsonSchemaOf(ratingSchema) })
  async rate(
    @Req() req: Request,
    @Res({ passthrough: true }) res: Response,
    @Param('id', uuidParam) id: string,
    @Body(new ZodPipe(ratingSchema)) body: RatingInput,
  ) {
    const u = user(req);
    const t = await fetchTicket(this.db.db, u, id);
    if (!t) throw appError(404, 'not_found', 'Ticket not found');
    if (t.status !== 'resolved' && t.status !== 'closed')
      throw appError(409, 'invalid_transition', 'Only a resolved ticket can be rated');
    const r = await this.db.db.execute(sql`
      INSERT INTO ratings (ticket_id, customer_id, score, comment) VALUES (${id}, ${u.id}, ${body.score}, ${body.comment ?? null})
      ON CONFLICT (ticket_id) DO NOTHING`);
    if ((r.rowCount ?? 0) === 0) throw appError(409, 'conflict', 'This ticket is already rated');
    res.status(201);
    return { score: body.score, comment: body.comment ?? null };
  }
}
